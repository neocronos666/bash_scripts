#!/bin/bash

HOST=$(hostname)
FECHA=$(date +"%Y%m%d_%H%M")

OUT="$HOME/Descargas/${HOST}_inventario_${FECHA}.txt"

exec > "$OUT"

echo "========================================================="
echo " INVENTARIO DEL SISTEMA"
echo "========================================================="
echo

echo "HOST:"
hostnamectl
echo

echo "========================================================="
echo "KERNEL"
echo "========================================================="
uname -a
echo

echo "========================================================="
echo "PAQUETES INSTALADOS (APT)"
echo "========================================================="
apt-mark showmanual | sort
echo

echo "========================================================="
echo "PAQUETES FLATPAK"
echo "========================================================="
flatpak list
echo

echo "========================================================="
echo "PAQUETES SNAP"
echo "========================================================="
snap list 2>/dev/null
echo

echo "========================================================="
echo "PYTHON"
echo "========================================================="
python3 --version
pip3 list
echo

echo "========================================================="
echo "PIPX"
echo "========================================================="
pipx list 2>/dev/null
echo

echo "========================================================="
echo "NODE"
echo "========================================================="
node -v 2>/dev/null
npm list -g --depth=0 2>/dev/null
echo

echo "========================================================="
echo "DOCKER"
echo "========================================================="
docker images 2>/dev/null
docker ps -a 2>/dev/null
echo

echo "========================================================="
echo "SERVICIOS ACTIVOS"
echo "========================================================="
systemctl list-unit-files --state=enabled
echo

echo "========================================================="
echo "ESPACIO EN DISCO"
echo "========================================================="
df -h
echo

echo "========================================================="
echo "DIRECTORIOS GRANDES EN HOME"
echo "========================================================="
du -sh ~/* 2>/dev/null | sort -h
echo

echo "========================================================="
echo "CACHE APT"
echo "========================================================="
du -sh /var/cache/apt 2>/dev/null
echo

echo "========================================================="
echo "CACHE USUARIO"
echo "========================================================="
du -sh ~/.cache 2>/dev/null
echo

echo "========================================================="
echo "FIN"
echo "========================================================="

echo
echo "Inventario guardado en:"
echo "$OUT"
